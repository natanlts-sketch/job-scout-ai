def get_lang() -> str:
    lang = st.session_state.get("ui_lang")
    if lang in {"en", "he"}:
        return lang
    return "he"  # default Hebrew


def set_lang(lang: str) -> None:
    if lang in {"en", "he"}:
        st.session_state["ui_lang"] = lang


def t(key: str, **kwargs: Any) -> str:
    lang = get_lang()
    text = STRINGS.get(lang, STRINGS["he"]).get(key) or STRINGS["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def apply_direction() -> None:
    if get_lang() == "he":
        st.markdown(
            """
            <style>
            .block-container, [data-testid="stMarkdownContainer"],
            label, p, h1, h2, h3, .stTextInput label {
              direction: rtl;
              text-align: right;
            }
            [data-testid="stSidebar"] { direction: rtl; text-align: right; }
            </style>
            """,
            unsafe_allow_html=True,
        )


def language_picker(key: str = "lang_picker") -> None:
    current = get_lang()
    choice = st.radio(
        t("ui_language"),
        options=["he", "en"],
        format_func=lambda x: "עברית" if x == "he" else "English",
        horizontal=True,
        index=0 if current == "he" else 1,
        key=key,
    )
    if choice != current:
        set_lang(choice)
        st.rerun()


def sync_lang_from_prefs(prefs: dict | None) -> None:
    if "ui_lang" in st.session_state:
        return
    if prefs and prefs.get("language") in {"en", "he"}:
        set_lang(prefs["language"])
    else:
        set_lang("he")
